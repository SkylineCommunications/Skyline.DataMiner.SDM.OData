namespace Skyline.DataMiner.SDM.OData
{
	/// <summary>
	/// Represents an OData sort direction.
	/// </summary>
	public enum ODataOrder
	{
		/// <summary>
		/// Indicates that no sort direction was specified.
		/// </summary>
		None,

		/// <summary>
		/// Represents ascending order.
		/// </summary>
		Ascending,

		/// <summary>
		/// Represents descending order.
		/// </summary>
		Descending,
	}
}
