namespace Skyline.DataMiner.SDM.OData
{
	/// <summary>
	/// Represents an OData string function.
	/// </summary>
	public enum ODataStringOperation
	{
		/// <summary>
		/// Represents the OData <c>substringof</c> function.
		/// </summary>
		SubStringOf,

		/// <summary>
		/// Represents the OData <c>endswith</c> function.
		/// </summary>
		EndsWith,

		/// <summary>
		/// Represents the OData <c>startswith</c> function.
		/// </summary>
		StartsWith,

		/// <summary>
		/// Represents the OData <c>length</c> function.
		/// </summary>
		Length,

		/// <summary>
		/// Represents the OData <c>indexof</c> function.
		/// </summary>
		IndexOf,

		/// <summary>
		/// Represents the OData <c>replace</c> function.
		/// </summary>
		Replace,

		/// <summary>
		/// Represents the OData <c>substring</c> function.
		/// </summary>
		Substring,

		/// <summary>
		/// Represents the OData <c>tolower</c> function.
		/// </summary>
		ToLower,

		/// <summary>
		/// Represents the OData <c>toupper</c> function.
		/// </summary>
		ToUpper,

		/// <summary>
		/// Represents the OData <c>trim</c> function.
		/// </summary>
		Trim,

		/// <summary>
		/// Represents the OData <c>concat</c> function.
		/// </summary>
		Concat,
	}
}
