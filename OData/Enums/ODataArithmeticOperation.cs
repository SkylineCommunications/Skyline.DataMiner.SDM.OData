		/// Represents the OData <c>mul</c> operator.
		/// </summary>
		Multiply,

		/// <summary>
		/// Represents the OData <c>div</c> operator.
		/// </summary>
		Divide,

		/// <summary>
		/// Represents the OData <c>mod</c> operator.
		/// </summary>
		Modulo,
	}
}
